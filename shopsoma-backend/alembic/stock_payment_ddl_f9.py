    "          FROM stock_reservations sr\n"
    "         WHERE sr.order_item_id = NEW.order_item_id\n"
    "           AND sr.state = 'active'\n"
    "           AND (sr.expires_at > now_at OR EXISTS (\n"
    "               SELECT 1 FROM payment_attempt_reservations ar\n"
    "               JOIN payment_attempts pa ON pa.id = ar.attempt_id\n"
