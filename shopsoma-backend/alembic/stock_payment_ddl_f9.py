    "            OR NEW.unit_price IS DISTINCT FROM OLD.unit_price\n"
    "            OR NEW.currency IS DISTINCT FROM OLD.currency) THEN\n"
    "        RAISE EXCEPTION 'reserved order item truth is immutable';\n"
    "    END IF;\n"
    "    RETURN NEW;\n"
    "END;\n"
    "$$ LANGUAGE plpgsql;\n"
